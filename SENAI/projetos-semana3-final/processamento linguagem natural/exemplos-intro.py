from sklearn.feature_extraction.text import CountVectorizer, TfidfVectorizer
textos = [
    'eu gosto de pizza',
    'eu gosto de sorvete',
    'pizza é deliciosa'
]
vetor = CountVectorizer()
X = vetor.fit_transform(textos)
print(vetor.get_feature_names_out())
print(X.toarray())

vetor = TfidfVectorizer() # Elimina o peso dos conectivos (de, o, a, etc.)
X = vetor.fit_transform(textos)
print(vetor.get_feature_names_out())
print(X.toarray())

from sklearn.naive_bayes import MultinomialNB

frases = [
    'gostei muito',
    'excelente produto',
    'péssimo produto',
    'odiei o produto'
    # Três frases coincidem na palavra 'produto'
]
rotulos = [
    'positivo',
    'positivo',
    'negativo',
    'negativo'
    # Duas frases com 'produto' são negativas e só uma é positiva. O rótulo para frases contendo 'produto' será 'negativo'.
]

vetor = CountVectorizer()
X = vetor.fit_transform(frases)

modelo = MultinomialNB()
modelo.fit(X, rotulos)

nova_frase = vetor.transform(['excelente produto']) # igual à frase de treinamento, portanto mesmo rótulo
print(modelo.predict(nova_frase)[0])

nova_frase = vetor.transform(['otimo produto']) # duas frases com 'produto' -> negativo, e uma frase com 'produto' -> positivo, portanto o rótulo de maior peso é o negativo
print(modelo.predict(nova_frase)[0])

from sklearn.pipeline import Pipeline

textos = [
    'time venceu campeonato',
    'o campeonato acabou',
    'governo anuncia medida',
    'novo celular lançado',
    'eleições começam amanhã',
    'vacina está em fase de testes',
    'a inflação diminuiu',
    'SENAI criou novos cursos gratuitos'
]
categorias = [ # Cada frase será rotulada com uma categoria
    'esporte',
    'esporte',
    'política',
    'tecnologia',
    'política',
    'saúde',
    'economia',
    'educação'
]
modelo = Pipeline([
    ('tfidf', TfidfVectorizer()),
    ('clf', MultinomialNB())
])

modelo.fit(textos, categorias)
print(modelo.predict(['novo campeonato de futebol'])[0])

