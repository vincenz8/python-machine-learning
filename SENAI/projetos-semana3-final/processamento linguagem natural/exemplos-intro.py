# Contando palavras - PLN (Processamento de Linguagem Natural)

# Tokenização: computador separa uma string (texto) em palavras
# Computadores não formam conceitos a partir de frases, elas precisam ser fragmentadas e analizadas por separado.
#   Cada fragmento -> Token

from collections import Counter

texto = 'Eu gosto de estudar Machine Learning'
palavras = texto.split()
print(palavras)

contador = Counter(palavras)
print(contador)

texto2 = 'gatos cachorros gatos cachorros gatos passarinhos'
palavras2 = texto2.split()
contador = Counter(palavras2)
print(contador)

